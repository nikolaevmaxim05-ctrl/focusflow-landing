// Generates src/components/ui/digitOutlines.ts: SVG outlines of the digits 0–9 in
// Manrope ExtraBold with overlapping contours removed. The Features block draws its
// big outlined step numbers from these paths, because stroking live text (text-stroke)
// shows every contour of a glyph, including the parts hidden inside overlaps.
//
// Run from the project root (the three packages are not project dependencies):
//
//   npm install --no-save opentype.js@1.3.4 wawoff2@2.0.1 pathkit-wasm@1.0.0
//   node scripts/generate-digit-outlines.mjs
//   npm prune
//
// The font comes from Google Fonts (the same static 800 cut next/font uses).
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");
const wawoff2 = require("wawoff2");
const initPathKit = require("pathkit-wasm/bin/pathkit.js");

const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Manrope:wght@800&display=swap";
// A browser user agent makes Google answer with woff2 files.
const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36";
const OUTPUT = resolve("src/components/ui/digitOutlines.ts");

async function downloadFont() {
  const css = await (
    await fetch(CSS_URL, { headers: { "User-Agent": USER_AGENT } })
  ).text();
  // The latin block is the last @font-face in the stylesheet.
  const latin = css.split("/* latin */").pop();
  const url = latin.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
  if (!url)
    throw new Error(
      "Could not find the latin woff2 url in the Google Fonts css",
    );
  const woff2 = Buffer.from(await (await fetch(url)).arrayBuffer());
  return Buffer.from(await wawoff2.decompress(woff2));
}

const ttf = await downloadFont();
const font = opentype.parse(
  ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength),
);
const PathKit = await initPathKit({
  wasmBinary: readFileSync(require.resolve("pathkit-wasm/bin/pathkit.wasm")),
});

const digits = [];
for (let digit = 0; digit <= 9; digit++) {
  const glyph = font.charToGlyph(String(digit));
  // Font units, y pointing down (SVG orientation); 1 decimal keeps the file small.
  const path = PathKit.FromSVGString(
    glyph.getPath(0, 0, font.unitsPerEm).toPathData(1),
  );
  path.setFillType(PathKit.FillType.WINDING);
  path.simplify(); // merges overlapping contours and self-intersections
  digits.push(
    `  { d: "${path.toSVGString()}", advance: ${glyph.advanceWidth} },`,
  );
  path.delete();
}

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-digit-outlines.mjs — do not edit by hand.
// ${font.names.fontFamily.en} ${font.names.fontSubfamily.en}: outlines of the digits 0–9
// with overlaps removed, in font units with y pointing down.

export const DIGIT_FONT = {
  unitsPerEm: ${font.unitsPerEm},
  ascender: ${font.ascender},
  descender: ${font.descender},
};

/** Index = digit. */
export const DIGITS: { d: string; advance: number }[] = [
${digits.join("\n")}
];
`,
);
console.log(
  `Wrote ${OUTPUT} (${font.names.fontFamily.en} ${font.names.fontSubfamily.en}, upm ${font.unitsPerEm})`,
);
